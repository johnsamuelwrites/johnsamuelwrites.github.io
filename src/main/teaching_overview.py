#!/usr/bin/env python3
"""Generate the teaching overview pages, in every site language.

The overview of every course taught since 2017 (``en/teaching/teaching.html``,
``fr/enseignement/enseignement.html`` and their six translations) is generated
whole, so the languages cannot drift and a new academic year is one edit:

* ``data/teaching/courses.csv``: one row per course offering (a course in one
  programme). ``taught`` is the years as recorded (``2017-`` ongoing,
  ``2017-2022``, ``2017, 2018, 2022``); ``pages`` lists each year's course
  directory under ``fr/enseignement/cours/`` (``2019:ProgSys``), whose English
  directory follows ``link_language_pairs.EN_NAME``; ``follows`` names the
  course it grew out of (``?id`` while only proposed). A course is current when
  ``taught`` is open. French and English text come from the row itself; the
  other languages take the course title from ``title_item`` (a Wikibase item,
  or a ``title:`` key of the translation table).
* ``data/translations/teaching-overview.csv``: every other string, one column
  per language (an empty cell means the English text).
* ``templates/teaching/overview.html``: the page shell and its styles. The
  navigation is copied from the teaching index next to each page, which is
  already translated.

Each page has a hero with summary figures; a timeline (an HTML column of names
beside an SVG of the years): one lane per course offering grouped by theme, a
bar for the years taught, a dot linking each year's course page and a line to
the course it grew out of; a summary of each academic year, shown by
``ui/teaching/teaching-timeline.js`` when a reader picks a year (the script only
shows, hides and dims, so every string comes from here); and the course cards.

Usage:
    python src/main/teaching_overview.py --check   # exit 1 if a page is stale
    python src/main/teaching_overview.py --apply   # write the pages
    python src/main/teaching_overview.py --notes   # rows flagged for review
"""

