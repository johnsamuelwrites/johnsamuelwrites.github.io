class Strings:
    """The translation table: ``get(key, language)`` falls back to English."""

    def __init__(self, path: Path) -> None:
        with path.open(encoding="utf-8", newline="") as handle:
            self.rows = {row["key"]: row for row in csv.DictReader(handle)}

    def has(self, key: str) -> bool:
        return key in self.rows

    def get(self, key: str, language: str) -> str:
        row = self.rows[key]
        return row.get(language) or row["en"]


@dataclass
class Course:
    row: dict
    years: list[int]
    open_ended: bool
    pages: list[tuple[int, str]]
    follows: list[tuple[str, bool]] = field(default_factory=list)  # (id, proposed)

    @property
    def id(self) -> str:
        return self.row["id"]

    @property
    def theme(self) -> str:
        return self.row["theme"]


@dataclass
class Site:
    root: Path
    courses: list[Course]
    latest: int
    strings: Strings
    labels: dict[str, dict[str, str]]

    def page(self, language: str) -> Path:
        return Path(self.strings.get("page_path", language))

    def text(self, key: str, language: str, **values) -> str:
        return self.strings.get(key, language).format(**values)

    def title(self, course: Course, language: str) -> str:
        if language in OWN_TEXT:
            return course.row[f"title_{language}"]
        item = course.row["title_item"]
        if item.startswith("title:") and self.strings.has(item):
            return self.strings.get(item, language)
        label = self.labels.get(item, {}).get(language, "").strip()
        return label or course.row["title_en"]

    def programme(self, course: Course, language: str) -> str:
        if language in OWN_TEXT:
            return course.row[f"programme_{language}"]
        english = course.row["programme_en"]
        key = f"programme:{english}"
        return self.strings.get(key, language) if self.strings.has(key) else english

    def phrase(self, course: Course, column: str, language: str) -> str:
        """A responsibility or role; ``Course instructor (Python)`` keeps its topic."""
        if language in OWN_TEXT:
            return course.row[f"{column}_{language}"]
        english = course.row[f"{column}_en"]
        if not english:
            return ""
        match = re.fullmatch(r"(.*?)(\s*\([^)]*\))?", english)
        base, topic = match.group(1), match.group(2) or ""
        key = f"phrase:{base}"
        return (self.strings.get(key, language) if self.strings.has(key) else base) + topic

    def lane_title(self, course: Course, language: str) -> str:
        """The title with its programme (and major), unless the title names it."""
        title = self.title(course, language)
        programme = self.programme(course, language)
        if programme and f"({programme}" not in title:
            suffix = programme + (f" - {course.row['major']}" if course.row["major"] else "")
            title = f"{title} ({suffix})"
        return title


def parse_taught(value: str, current_year: int) -> tuple[list[int], bool]:
    value = value.strip()
    if re.fullmatch(r"\d{4}-", value):
        return list(range(int(value[:4]), current_year + 1)), True
    if re.fullmatch(r"\d{4}-\d{4}", value):
        first, last = map(int, value.split("-"))
        return list(range(first, last + 1)), False
    if re.fullmatch(r"\d{4}(\s*,\s*\d{4})*", value):
        return [int(year) for year in re.findall(r"\d{4}", value)], False
    raise ValueError(f"unreadable taught years: {value!r}")


def current_year(repo_root: Path) -> int:
    years = [
        int(path.name)
        for root in (FR_COURSES, EN_COURSES)
        for path in (repo_root / root).glob("[0-9][0-9][0-9][0-9]")
        if path.is_dir()
    ]
    return max(years)


def load_labels(repo_root: Path) -> dict[str, dict[str, str]]:
    path = repo_root / LABELS
    if not path.is_file():
        return {}
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return {row["identifier"]: row for row in csv.DictReader(handle)}


def load(repo_root: Path) -> Site:
    latest = current_year(repo_root)
    strings = Strings(repo_root / STRINGS)
    labels = load_labels(repo_root)
    courses, errors = [], []
    with (repo_root / DATA).open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    ids = [row["id"] for row in rows]
    for duplicate in sorted({value for value in ids if ids.count(value) > 1}):
        errors.append(f"duplicate id {duplicate}")
    for row in rows:
        try:
            years, open_ended = parse_taught(row["taught"], latest)
        except ValueError as error:
            errors.append(f"{row['id']}: {error}")
            continue
        pages = []
        for entry in row["pages"].split():
            year, directory = entry.split(":", 1)
            pages.append((int(year), directory))
            if not page_paths(repo_root, int(year), directory):
                errors.append(f"{row['id']}: no course page for {entry}")
        if row["theme"] not in THEMES:
            errors.append(f"{row['id']}: unknown theme {row['theme']!r}")
        item = row.get("title_item", "")
        if item.startswith("title:") and not strings.has(item):
            errors.append(f"{row['id']}: no translation row {item!r}")
        if item.startswith("Q") and labels and item not in labels:
            errors.append(f"{row['id']}: unknown Wikibase item {item}")
        follows = [(value.lstrip("?"), value.startswith("?")) for value in row["follows"].split()]
        for other, _ in follows:
            if other not in ids:
                errors.append(f"{row['id']}: follows unknown id {other!r}")
        active = sorted(set(years) | {year for year, _ in pages})
        courses.append(Course(row, active, open_ended, pages, follows))
    if errors:
        raise SystemExit("data/teaching/courses.csv:\n  " + "\n  ".join(errors))
    return Site(repo_root, courses, latest, strings, labels)


def page_paths(repo_root: Path, year: int, directory: str) -> dict[str, Path]:
    """The existing index pages of a year's course, by language."""
    found = {}
    french = FR_COURSES / str(year) / directory / "index.html"
    english = EN_COURSES / str(year) / EN_NAME.get(directory, directory) / "index.html"
    if (repo_root / french).is_file():
        found["fr"] = french
    if (repo_root / english).is_file():
        found["en"] = english
    return found


def relative(page: Path, target: Path) -> str:
    return os.path.relpath(target, page.parent).replace(os.sep, "/")


def course_href(site: Site, language: str, year: int, directory: str) -> tuple[str, str]:
    """``(href, hreflang)`` of a year's course page: the page's language, else English, else French."""
    paths = page_paths(site.root, year, directory)
    chosen = next(code for code in (language, "en", "fr") if code in paths)
    href = relative(site.page(language), paths[chosen])
    if chosen == language and not href.startswith("."):
        href = "./" + href
    return href, ("" if chosen == language else chosen)


def esc(value: str) -> str:
    """Escape for text and double-quoted attributes; apostrophes stay as written."""
    return html.escape(value, quote=False).replace('"', "&quot;")


def academic(year: int) -> str:
    return f"{year}-{year + 1}"


def hours_value(text: str) -> float | None:
    numbers = [float(value) for value in re.findall(r"\d+(?:\.\d+)?", text)]
    return sum(numbers) / len(numbers) if numbers else None


def ordered(courses: list[Course]) -> list[Course]:
    position = {theme: index for index, theme in enumerate(THEMES)}
    return sorted(courses, key=lambda course: (position[course.theme], course.years[0], courses.index(course)))


def runs(years: list[int]) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for year in years:
        if result and result[-1][1] == year - 1:
            result[-1] = (result[-1][0], year)
        else:
            result.append((year, year))
    return result


def timeline(site: Site, language: str, first: int, last: int) -> str:
    """The course names as an HTML column beside an SVG of the years.

    Both are drawn in the same units: each row's height in the list and in the
    SVG comes from the same constants, and ``--u`` (CSS) scales them alike, so
    the rows line up while only the years scroll on a narrow screen.
    """
    courses = site.courses
    years = list(range(first, last + 1))
    width = COLUMN * len(years) + 12
    x_of = lambda year: (year - first) * COLUMN + COLUMN / 2  # noqa: E731
    labels: list[str] = [f'<li class="timeline-header" style="--h:{HEADER}"></li>']
    rows: list[str] = []
    lane_y: dict[str, float] = {}
    y = HEADER
    for theme, (colour, _icon) in THEMES.items():
        members = [course for course in ordered(courses) if course.theme == theme]
        if not members:
            continue
        labels.append(
            f'<li class="theme-row" data-theme="{theme}" style="--h:{GROUP_ROW};--theme:{colour}">'
            f'<span class="theme-swatch"></span>{esc(site.text("theme:" + theme, language))}</li>'
        )
        y += GROUP_ROW
        for course in members:
            centre = y + LANE / 2
            lane_y[course.id] = centre
            title = site.lane_title(course, language)
            state = "current" if course.open_ended else "past"
            data = f'data-id="{course.id}" data-theme="{theme}" data-years="{" ".join(map(str, course.years))}"'
            labels.append(
                f'<li class="lane lane-{state}" {data} style="--h:{LANE}" '
                f'title="{esc(title)} — {esc(course.row["taught"])}"><span>{esc(title)}</span></li>'
            )
            parts = [f'<g class="lane lane-{state}" {data} style="--theme:{colour}">', f"<title>{esc(title)}</title>"]
            for start, end in runs(course.years):
                x = (start - first) * COLUMN + 6
                parts.append(
                    f'<rect class="run" x="{x}" y="{centre - 7}" width="{(end - start + 1) * COLUMN - 12}" height="14" rx="7" />'
                )
            for year, directory in course.pages:
                href, hreflang = course_href(site, language, year, directory)
                extra = f' hreflang="{hreflang}"' if hreflang else ""
                label = site.text("page_of", language, title=title, year=academic(year))
                parts.append(
                    f'<a href="{esc(href)}"{extra} aria-label="{esc(label)}">'
                    f'<circle class="dot" cx="{x_of(year)}" cy="{centre}" r="6" /></a>'
                )
            parts.append("</g>")
            rows.append("".join(parts))
            y += LANE
    height = y + 10
    labels.append('<li class="timeline-footer" style="--h:10"></li>')
    lineage = []
    for course in courses:
        for other, proposed in course.follows:
            # Inside the successor's first year column, so it never reaches the names.
            left = (course.years[0] - first) * COLUMN
            y0, y1 = lane_y[other], lane_y[course.id]
            cls = "lineage proposed" if proposed else "lineage"
            lineage.append(
                f'<path class="{cls}" data-from="{other}" data-to="{course.id}" '
                f'd="M {left + 2} {y0} C {left + 16} {y0}, {left + 2} {y1}, {left + 16} {y1}" />'
            )
    columns = []
    for year in years:
        x = (year - first) * COLUMN
        now = " year-now" if year == last else ""
        columns.append(
            f'<g class="year-col{now}" data-select-year="{year}">'
            f'<rect x="{x}" y="0" width="{COLUMN}" height="{height}" />'
            f'<text class="year-label" x="{x + COLUMN / 2}" y="26">{year}</text>'
            f"<title>{esc(site.text('academic_year', language, year=academic(year)))}</title></g>"
        )
    svg = (
        f'<svg class="timeline-svg" viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="{esc(site.text("timeline", language, first=first, last=last))}" xmlns="http://www.w3.org/2000/svg">\n'
        + "\n".join(columns)
        + '\n<g class="lineages">' + "".join(lineage) + "</g>\n"
        + "\n".join(rows)
        + "\n</svg>"
    )
    return (
        f'<div class="timeline-frame"><div class="timeline-body" style="--years-w:{width}">\n'
        f'<ol class="timeline-labels">\n' + "\n".join(labels) + "\n</ol>\n"
        f'<div class="timeline-scroll">\n{svg}\n</div>\n</div></div>'
    )


def year_summaries(site: Site, language: str, first: int, last: int) -> str:
    courses = site.courses
    programmes_all = {site.programme(course, language) for course in courses if site.programme(course, language)}
    blocks = [
        '<div class="year-summary" data-year="all"><p>'
        + esc(site.text("overview", language, first=first, last=last, courses=len(courses), programmes=len(programmes_all)))
        + "</p></div>"
    ]
    for year in range(first, last + 1):
        active = [course for course in courses if year in course.years]
        if not active:
            continue
        hours = [hours_value(course.row["hours"]) for course in active]
        known = round(sum(value for value in hours if value is not None))
        hours_text = site.text("hours" if all(value is not None for value in hours) else "hours_min", language, h=known)
        programmes = sorted({site.programme(course, language) for course in active if site.programme(course, language)})
        spoken = sorted({code for course in active for code in course.row["instruction"].split()})
        new = [site.lane_title(course, language) for course in active if course.years[0] == year and year != first]
        ended = [site.lane_title(course, language) for course in active if course.years[-1] == year and not course.open_ended]
        lines = [
            f"<h3>{esc(site.text('academic_year', language, year=academic(year)))}</h3>",
            f'<p class="year-figures"><strong>{esc(site.text("courses_n", language, n=len(active)))}</strong> · {esc(hours_text)}</p>',
            f"<p>{esc(site.text('programmes', language, list=', '.join(programmes)))}</p>",
            f"<p>{esc(site.text('languages', language, list=', '.join(site.text('lang_name:' + code, language) for code in spoken)))}</p>",
        ]
        if new:
            lines.append(f'<p class="year-new">{esc(site.text("new", language, list=", ".join(new)))}</p>')
        if ended:
            lines.append(f'<p class="year-ended">{esc(site.text("ended", language, list=", ".join(ended)))}</p>')
        blocks.append(f'<div class="year-summary" data-year="{year}" hidden>' + "".join(lines) + "</div>")
    return "\n".join(blocks)


def card(site: Site, course: Course, language: str) -> str:
    colour, icon = THEMES[course.theme]
    links = [course_href(site, language, year, directory) + (year,) for year, directory in course.pages]
    title = site.title(course, language) if language in OWN_TEXT else site.lane_title(course, language)
    if links:
        href, hreflang, _ = links[-1]
        extra = f' hreflang="{hreflang}"' if hreflang else ""
        heading = f'<a href="{esc(href)}"{extra} class="course-title">{esc(title)}</a>'
    else:
        heading = f'<span class="course-title">{esc(title)}</span>'
    end = site.text("label_end", language)
    details = []

    def add(key: str, value: str) -> None:
        if value:
            details.append(f"<li><b>{esc(site.text('field:' + key, language))}{end}</b> {esc(value)}</li>")

    add("taught", course.row["taught"])
    add("programme", site.programme(course, language))
    add("major", course.row["major"])
    add("study_year", course.row["study_year"])
    add("responsibility", site.phrase(course, "responsibility", language))
    add("roles", site.phrase(course, "roles", language))
    add("ects", f"{course.row['ects']} ECTS" if course.row["ects"] else "")
    add("hours", f"{course.row['hours']} {site.text('hours_unit', language)}" if course.row["hours"] else "")
    if links:
        anchors = "".join(
            f'<a href="{esc(href)}"' + (f' hreflang="{hreflang}"' if hreflang else "") + f">{year}</a>"
            for href, hreflang, year in links
        )
        details.append(
            f'<li><b>{esc(site.text("field:pages", language))}{end}</b><div class="course-links">{anchors}</div></li>'
        )
    add("instruction", ", ".join(site.text("card_lang:" + code, language) for code in sorted(course.row["instruction"].split())))
    return (
        f'<div class="course-card" data-id="{course.id}" data-theme="{course.theme}" '
        f'data-years="{" ".join(map(str, course.years))}" style="--theme:{colour}">'
        f'<div class="course-icon"><svg viewBox="0 0 24 24" fill="none" stroke="{colour}" stroke-width="2">{ICONS[icon]}</svg></div>'
        f"{heading}"
        f'<ul class="course-details">{"".join(details)}</ul></div>'
    )


def region(site: Site, language: str) -> str:
    courses, latest = site.courses, site.latest
    first = min(course.years[0] for course in courses)
    current = [course for course in courses if course.open_ended]
    past = [course for course in courses if not course.open_ended]
    programmes = {site.programme(course, language) for course in courses if site.programme(course, language)}
    stats = [
        (latest - first + 1, site.text("stat_years", language)),
        (len(courses), site.text("stat_courses", language)),
        (len([course for course in courses if latest in course.years]), site.text("stat_current", language, year=academic(latest))),
        (len(programmes), site.text("stat_programmes", language)),
    ]
    stat_html = "".join(
        f'<div class="hero-stat"><span class="hero-stat-value">{value}</span>'
        f'<span class="hero-stat-label">{esc(label)}</span></div>'
        for value, label in stats
    )
    year_buttons = [
        f'<button type="button" class="year-btn" data-select-year="all" aria-pressed="true">{esc(site.text("all", language))}</button>'
    ] + [
        f'<button type="button" class="year-btn" data-select-year="{year}" aria-pressed="false">{year}-{str(year + 1)[2:]}</button>'
        for year in range(first, latest + 1)
    ]
    theme_buttons = [
        f'<button type="button" class="theme-btn" data-theme="{theme}" aria-pressed="false" style="--theme:{colour}">'
        f'<span class="theme-dot"></span>{esc(site.text("theme:" + theme, language))}</button>'
        for theme, (colour, _icon) in THEMES.items()
        if any(course.theme == theme for course in courses)
    ]
    return "\n".join(
        [
            '<div class="teaching-overview">',
            '<section class="hero"><div class="hero-content">'
            f"<h1>{esc(site.text('h1', language))}</h1><p>{esc(site.text('intro', language, first=first))}</p></div>"
            f'<div class="hero-stats">{stat_html}</div></section>',
            '<div class="container">',
            '<section class="timeline-section">',
            f'<div class="section-header"><h2>{esc(site.text("timeline", language, first=first, last=latest))}</h2></div>',
            f'<p class="timeline-hint">{esc(site.text("hint", language))}</p>',
            '<div class="timeline-controls" hidden>'
            f'<div class="control-row" role="group" aria-label="{esc(site.text("years", language))}">{"".join(year_buttons)}</div>'
            f'<div class="control-row" role="group" aria-label="{esc(site.text("themes", language))}">{"".join(theme_buttons)}</div></div>',
            f'<div class="year-summaries" aria-live="polite">\n{year_summaries(site, language, first, latest)}\n</div>',
            timeline(site, language, first, latest),
            "</section>",
            f'<div class="section-header"><h2>{esc(site.text("current", language))}</h2></div>',
            '<div class="course-grid">\n' + "\n".join(card(site, course, language) for course in current) + "\n</div>",
            f'<div class="section-header"><h2>{esc(site.text("past", language))}</h2></div>',
            '<div class="course-grid">\n' + "\n".join(card(site, course, language) for course in past) + "\n</div>",
            "</div>",
            "</div>",
        ]
    )


def navigation(site: Site, language: str) -> str:
    """The site navigation, taken from the teaching index in the same directory."""
    page = site.page(language)
    index = (site.root / page.parent / "index.html").read_text(encoding="utf-8")
    nav = index[index.index('<nav class="site-navigation"'): index.index("</nav>")]
    name = re.search(r'<a class="nav-name" href="([^"]*)"', nav).group(1)
    links = re.findall(r'<li>\s*<a href="([^"]*)">\s*(.*?)\s*</a>\s*</li>', nav, flags=re.S)
    items = "\n".join(
        '                    <li property="itemListElement" typeof="ListItem">\n'
        f'                        <a property="item" typeof="WebPage" href="{href}">\n'
        f'                            <span property="name">{label}</span>\n'
        "                        </a>\n"
        "                    </li>"
        for href, label in links
    )
    return (
        "        <nav>\n"
        '            <div class="nav-container">\n'
        '                <div class="nav-left">\n'
        f'                    <a href="{name}" class="nav-title">John Samuel</a>\n'
        f'                    <a href="./{page.name}" class="nav-subtitle">{esc(site.text("subtitle", language))}</a>\n'
        "                </div>\n"
        '                <ul class="breadcrumb" typeof="BreadcrumbList">\n'
        f"{items}\n"
        "                </ul>\n"
        "            </div>\n"
        "        </nav>"
    )


def footer(site: Site, language: str) -> str:
    page = site.page(language)
    buttons = "\n".join(
        f'                    <a href="{relative(page, site.page(code)) if code != language else page.name}" '
        f'class="lang-btn{" active" if code == language else ""}" hreflang="{code}" lang="{code}">{ENDONYMS[code]}</a>'
        for code in ORDER
    )
    return (
        "        <footer>\n"
        '            <div class="footer-content">\n'
        f'                <div class="language-selector" role="navigation" aria-label="{esc(site.text("field:instruction", language))}">\n'
        f"{buttons}\n"
        "                </div>\n"
        f"                <p>{esc(site.text('footer', language))}</p>\n"
        '                <a rel="license" href="http://creativecommons.org/licenses/by-sa/4.0/">\n'
        f'                    <img src="./../../images/license.png" alt="{esc(site.text("license_alt", language))}" class="license-img" />\n'
        "                </a>\n"
        "            </div>\n"
        "        </footer>"
    )


def render_page(site: Site, language: str, template: str) -> str:
    page = site.page(language)
    alternates = "\n".join(
        f'        <link rel="alternate" hreflang="{code}" href="{relative(page, site.page(code))}" />'
        for code in ORDER
        if code != language
    )
    values = {
        "lang": language,
        "title": esc(site.text("title", language)),
        "alternates": alternates,
        "nav": navigation(site, language),
        "region": GENERATED + "\n" + region(site, language),
        "footer": footer(site, language),
    }
    return re.sub(r"\{\{(\w+)\}\}", lambda match: values[match.group(1)], template)


def process(repo_root: Path, apply: bool) -> int:
    site = load(repo_root)
    template = (repo_root / TEMPLATE).read_text(encoding="utf-8")
    stale = []
    for language in ORDER:
        relative_path = site.page(language)
        path = repo_root / relative_path
        updated = render_page(site, language, template)
        original = path.read_text(encoding="utf-8") if path.is_file() else ""
        if updated == original:
            continue
        stale.append(relative_path.as_posix())
        if apply:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(updated, encoding="utf-8")
            print(f"wrote {relative_path}")
    if stale and not apply:
        print(
            "stale teaching overview page(s): " + ", ".join(stale)
            + "\nrun: python src/main/teaching_overview.py --apply",
            file=sys.stderr,
        )
        return 1
    return 0


def notes(repo_root: Path) -> int:
    for course in load(repo_root).courses:
        if course.row["notes"]:
            print(f"{course.id:14} {course.row['notes']}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 if a page does not match the data")
    mode.add_argument("--apply", action="store_true", help="write the pages from the data")
    mode.add_argument("--notes", action="store_true", help="list the rows flagged for review")
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    args = parser.parse_args()
    root = args.repo_root.resolve()
    if args.notes:
        return notes(root)
    return process(root, args.apply)


if __name__ == "__main__":
    sys.exit(main())
